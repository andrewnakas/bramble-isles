def glyph(c):
    rows = G.get(c, G['?'])
    return np.array([[ch == '#' for ch in r] for r in rows], bool)


def bold(m):
    out = m.copy()
    out[:, 1:] |= m[:, :-1]
    return out


def cell(c, heavy=False, dy=0, dx=1):
    """8x8 mask with the glyph placed at (dx, dy)."""
    g = glyph(c)
    if heavy:
        g = bold(g)
    m = np.zeros((8, 8), bool)
    h, w = g.shape
    w = min(w, 8 - dx)
    m[dy:dy + h, dx:dx + w] = g[:, :w]
    return m


def ring(m):
    p = np.pad(m, 1)
    near = np.zeros_like(m)
    for dy in (0, 1, 2):
        for dx in (0, 1, 2):
            near |= p[dy:dy + m.shape[0], dx:dx + m.shape[1]]
    return near & ~m


def outlined(m, body, edge, bg=0):
    out = np.full(m.shape, bg, np.uint8)
    out[ring(m)] = edge
    out[m] = body
    return out


def line(text, heavy=False, gap=1):
    """Mask of a word in our face, 7 high."""
    cols = []
    for ch in text:
        g = glyph(ch)
        if heavy:
            g = np.hstack([bold(g), np.zeros((7, 1), bool)])
        cols += [g, np.zeros((7, gap), bool)]
    return np.hstack(cols[:-1]) if cols else np.zeros((7, 0), bool)


def tall(c):
    """8x16 mask: our glyph doubled vertically with a waist (tall face for the big letters)."""
    g = glyph(c)
    m = np.zeros((16, 8), bool)
    rows = [0, 1, 1, 2, 2, 3, 3, 3, 4, 4, 5, 5, 6, 6]           # 7 rows -> 14, middle row tripled
    m[1:15, 1:6] = g[rows]
    return m



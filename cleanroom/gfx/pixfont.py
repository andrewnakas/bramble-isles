def glyph(c):
    rows = _F.get(c) or _F.get(c.upper()) or _F['?']
    return np.array([[ch == '#' for ch in r] for r in rows.split()], bool)


def cell(c, w=8, h=8, bold=True, dx=None, dy=None):
    g = glyph(c)
    if bold:
        b = np.zeros((7, 6), bool)
        b[:, :5] |= g
        b[:, 1:] |= g
        g = b
    out = np.zeros((h, w), bool)
    x = (w - g.shape[1]) // 2 if dx is None else dx
    y = (h - 7) // 2 if dy is None else dy
    out[y:y + 7, x:x + g.shape[1]] = g[:h - y, :w - x]
    return out


def line(text, bold=True, gap=1):
    """Proportional line: (7, W) bool array."""
    parts = []
    for c in text:
        g = cell(c, 6 if bold else 5, 7, bold, 0, 0)
        if c == ' ':
            g = g[:, :3]
        parts += [g, np.zeros((7, gap), bool)]
    return np.hstack(parts[:-1]) if parts else np.zeros((7, 0), bool)
